#include "font8x8.h"

/* Minimal 8x8 font: space, digits, A-Z, a-z subset */
static const u8 font_space[8] = {0};

static const u8 font_digits[10][8] = {
    {0x3C,0x66,0x6E,0x76,0x66,0x66,0x3C,0}, /* 0 */
    {0x18,0x38,0x18,0x18,0x18,0x18,0x7E,0},
    {0x3C,0x66,0x06,0x0C,0x30,0x60,0x7E,0},
    {0x3C,0x66,0x06,0x1C,0x06,0x66,0x3C,0},
    {0x0C,0x1C,0x2C,0x4C,0x7E,0x0C,0x0C,0},
    {0x7E,0x60,0x7C,0x06,0x06,0x66,0x3C,0},
    {0x1C,0x30,0x60,0x7C,0x66,0x66,0x3C,0},
    {0x7E,0x06,0x0C,0x18,0x30,0x30,0x30,0},
    {0x3C,0x66,0x66,0x3C,0x66,0x66,0x3C,0},
    {0x3C,0x66,0x66,0x3E,0x06,0x0C,0x38,0},
};

static const u8 font_A[8] = {0x18,0x3C,0x66,0x66,0x7E,0x66,0x66,0};
static const u8 font_V[8] = {0x66,0x66,0x66,0x66,0x66,0x3C,0x18,0};

const u8* font8x8_glyph(char c) {
    if (c >= '0' && c <= '9') {
        return font_digits[c - '0'];
    }
    if (c == ' ') {
        return font_space;
    }
    if (c == 'A' || c == 'a') {
        return font_A;
    }
    if (c == 'V' || c == 'v') {
        return font_V;
    }
    return font_space;
}
